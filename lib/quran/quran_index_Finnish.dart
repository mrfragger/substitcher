- Ikuisesti ylösnousemuksen päivään asti, kuka on Jumalan ohella jumala, joka voisi tuoda teille? (سَرْمَدًا إِلَى يَوْمِ الْقِيَامَةِ مَنْ إِلَهٌ غَيْرُ اللَّهِ يَأْتِيكُم) 28:71; 28:72
- Joka tekee hyvää, mies tai nainen, ja on uskovainen. (مَنْ عَمِلَ صَالِحًا مِّن ذَكَرٍ أَوْ أُنثَى وَهُوَ مُؤْمِنٌ) 16:97; 40:40
- Ne, jotka kääntävät pois Jumalan tieltä ja haluavat sen mutkikkaaksi, ja he eivät usko tulevaan elämään. (الَّذِينَ يَصُدُّونَ عَن سَبِيلِ اللَّهِ وَيَبْغُونَهَا عِوَجًا وَهُم بِالْآخِرَةِ) 7:45; 11:19
- Syökää missä haluatte, mutta älkää lähestykö tätä puuta, jottette tule väärintekijöiksi. (حَيْثُ شِئْتُمَا وَلَا تَقْرَبَا هَذِهِ الشَّجَرَةَ فَتَكُونَا مِنَ الظَّالِمِينَ) 2:35; 7:19
- Sano: "Kansani! Toimikaa asemassanne, minäkin toimin, ja te tulette pian tietämään." (قُلْ يَاقَوْمِ اعْمَلُوا عَلَى مَكَانَتِكُمْ إِنِّي عَامِلٌ فَسَوْفَ تَعْلَمُونَ) 6:135; 39:39
- Totisesti, tappiolla ovat ne, jotka menettivät itsensä ja perheensä ylösnousemuksen päivänä, oi. (إِنَّ الْخَاسِرِينَ الَّذِينَ خَسِرُوا أَنفُسَهُمْ وَأَهْلِيهِمْ يَوْمَ الْقِيَامَةِ أَلَا) 39:15; 42:45
- Se, joka on oikealla tiellä, on oikealla tiellä itselleen, ja se, joka eksyy, eksyy itselleen, ja. (يَهْتَدِي لِنَفْسِهِ وَمَن ضَلَّ فَإِنَّمَا يَضِلُّ عَلَيْهَا وَمَا) 10:108; 39:41
- Ja ne, jotka eivät usko, sanovat: "Miksi hänelle ei ole lähetetty merkkiä Herraltaan?" (وَيَقُولُ الَّذِينَ كَفَرُوا لَوْلَا أُنزِلَ عَلَيْهِ آيَةٌ مِّن رَّبِّهِ) 13:7; 13:27
- Hän, joka on tehnyt teille yön, että lepäisitte siinä, ja päivän, että näkisitte, totisesti. (الَّذِي جَعَلَ لَكُمُ اللَّيْلَ لِتَسْكُنُوا فِيهِ وَالنَّهَارَ مُبْصِرًا إِنَّ) 10:67; 40:61
- Ennen kuin päivä koittaa, jolloin ei ole kauppaa eikä ystävyyttä. (مِّن قَبْلِ أَن يَأْتِيَ يَوْمٌ لَّا بَيْعٌ فِيهِ وَلَا) 2:254; 14:31
- Että he ajattelisivat, ettei heidän toverinsa ole hullu, hän on vain selvä varoittaja. (يَتَفَكَّرُوا مَا بِصَاحِبِهِم مِّن جِنَّةٍ إِنْ هُوَ إِلَّا نَذِيرٌ) 7:184; 34:46
- Ikuisesti siinä, rangaistusta ei lievennetä heille, eikä heille anneta armonaikaa. (خَالِدِينَ فِيهَا لَا يُخَفَّفُ عَنْهُمُ الْعَذَابُ وَلَا هُمْ يُنظَرُونَ) 2:162; 3:88
- Älä kohota silmiäsi siihen, mitä Me olemme antanut nautinnoksi joillekin heistä. (لَا تَمُدَّنَّ عَيْنَيْكَ إِلَى مَا مَتَّعْنَا بِهِ أَزْوَاجًا مِّنْهُمْ) 15:88; 20:131
- Älkääkä vähentäkö ihmisten tavaroita, älkääkä aiheuttako turmelusta maan päällä. (وَلَا تَبْخَسُوا النَّاسَ أَشْيَاءَهُمْ وَلَا تَعْثَوْا فِي الْأَرْضِ مُفْسِدِينَ) 11:85; 26:183
- Ja rauha olkoon hänelle sinä päivänä, kun hän syntyi, ja sinä päivänä, kun hän kuolee, ja sinä päivänä, kun hänet herätetään elävänä. (وَسَلَامٌ عَلَيْهِ يَوْمَ وُلِدَ وَيَوْمَ يَمُوتُ وَيَوْمَ يُبْعَثُ حَيًّا) 19:15; 19:33
- Kansani! Toimikaa asemassanne, minäkin toimin, ja te tulette pian tietämään, kuka. (يَاقَوْمِ اعْمَلُوا عَلَى مَكَانَتِكُمْ إِنِّي عَامِلٌ فَسَوْفَ تَعْلَمُونَ مَن) 6:135; 11:93
- Eikä lähettiläälle ole annettu tuoda merkkiä muutoin kuin Jumalan luvalla. (وَمَا كَانَ لِرَسُولٍ أَن يَأْتِيَ بِآيَةٍ إِلَّا بِإِذْنِ اللَّهِ) 13:38; 40:78
- Sitten jokaiselle sielulle maksetaan täysin se, mitä se on ansainnut, eikä heille tehdä vääryyttä. (ثُمَّ تُوَفَّى كُلُّ نَفْسٍ مَّا كَسَبَتْ وَهُمْ لَا يُظْلَمُونَ) 2:281; 3:161
- Mies tai nainen, ja hän on uskovainen, he saavat astua paratiisiin. (مِن ذَكَرٍ أَوْ أُنثَى وَهُوَ مُؤْمِنٌ فَأُولَئِكَ يَدْخُلُونَ الْجَنَّةَ) 4:124; 40:40
- Hän ei ole ottanut lasta, eikä Hänellä ole kumppania valtakunnassa. (لَمْ يَتَّخِذْ وَلَدًا وَلَمْ يَكُن لَّهُ شَرِيكٌ فِي الْمُلْكِ) 17:111; 25:2
- Ja se, jota Jumala ohjaa, on oikealla tiellä, ja se, jonka Hän eksyttää. (وَمَن يَهْدِ اللَّهُ فَهُوَ الْمُهْتَدِ وَمَن يُضْلِلْ فَلَن تَجِدَ) 17:97; 18:17
- Katso, kuinka he esittävät sinulle vertauksia ja eksyvät, eivätkä he löydä tietä. (انظُرْ كَيْفَ ضَرَبُوا لَكَ الْأَمْثَالَ فَضَلُّوا فَلَا يَسْتَطِيعُونَ سَبِيلًا) 17:48; 25:9
- Sano: "Minä pelkään, jos olen tottelematon Herralleni, suuren päivän rangaistusta." (قُلْ إِنِّي أَخَافُ إِنْ عَصَيْتُ رَبِّي عَذَابَ يَوْمٍ عَظِيمٍ) 6:15; 39:13
- Heidän häpeänsä paljastuivat heille, ja he alkoivat peittää itseään paratiisin lehdillä. (بَدَتْ لَهُمَا سَوْآتُهُمَا وَطَفِقَا يَخْصِفَانِ عَلَيْهِمَا مِن وَرَقِ الْجَنَّةِ) 7:22; 20:121
- Ja kutsukaa niitä, joita voitte, Jumalan ohella, jos olette oikeassa. (وَادْعُوا مَنِ اسْتَطَعْتُم مِّن دُونِ اللَّهِ إِن كُنتُمْ صَادِقِينَ) 10:38; 11:13
- Kaikki, mitä maan päällä on, ja saman verran lisää lunastaakseen itsensä. (مَّا فِي الْأَرْضِ جَمِيعًا وَمِثْلَهُ مَعَهُ لِيَفْتَدُوا بِهِ مِنْ) 5:36; 39:47
- Pitäkää lujasti se, minkä Me olemme teille antaneet, ja muistakaa, mitä siinä on, jotta pelkäisitte Jumalaa. (خُذُوا مَا آتَيْنَاكُم بِقُوَّةٍ وَاذْكُرُوا مَا فِيهِ لَعَلَّكُمْ تَتَّقُونَ) 2:63; 7:171
- Teettekö haureutta, jota kukaan maailmoista ei ole tehnyt ennen teitä? (أَتَأْتُونَ الْفَاحِشَةَ مَا سَبَقَكُم بِهَا مِنْ أَحَدٍ مِّنَ الْعَالَمِينَ) 7:80; 29:28
- Jumalalle kuuluu kaikki taivaissa ja maan päällä, ja Jumala on. (وَلِلَّهِ مَا فِي السَّمَاوَاتِ وَمَا فِي الْأَرْضِ وَكَانَ اللَّهُ) 4:126; 4:131
- Heidän pahat tekonsa saavuttivat heidät, ja se, mistä he pilkkaa tekivät, kietoutui heidän ympärilleen. (سَيِّئَاتُ مَا عَمِلُوا وَحَاقَ بِهِم مَّا كَانُوا بِهِ يَسْتَهْزِئُونَ) 16:34; 45:33
- Lähettiläs teidän keskuudestanne, joka lukee teille Meidän merkkimme, puhdistaa teidät ja opettaa teille Kirjaa ja viisautta. (رَسُولًا مِّنكُمْ يَتْلُو عَلَيْكُمْ آيَاتِنَا وَيُزَكِّيكُمْ وَيُعَلِّمُكُمُ الْكِتَابَ وَالْحِكْمَةَ) 2:151; 62:2
- Siitä pursusi kaksitoista lähdettä; jokainen ryhmä tunsi juomapaikkansa. (مِنْهُ اثْنَتَا عَشْرَةَ عَيْنًا قَدْ عَلِمَ كُلُّ أُنَاسٍ مَّشْرَبَهُمْ) 2:60; 7:160
- Pelkkää arvelua, ja arvelu ei totuudessa hyödytä mitään. (إِلَّا ظَنًّا إِنَّ الظَّنَّ لَا يُغْنِي مِنَ الْحَقِّ شَيْئًا) 10:36; 53:28
- Kun olen täydentänyt hänet ja puhaltanut häneen henkeäni, langetkaa hänen eteensä kumartaen. (فَإِذَا سَوَّيْتُهُ وَنَفَخْتُ فِيهِ مِن رُّوحِي فَقَعُوا لَهُ سَاجِدِينَ) 15:29; 38:72
- Kenelle kuuluu tämän maailman hyvä loppu? Totisesti, väärintekijät eivät menesty. (مَن تَكُونُ لَهُ عَاقِبَةُ الدَّارِ إِنَّهُ لَا يُفْلِحُ الظَّالِمُونَ) 6:135; 28:37
- Hän, joka loi taivaat ja maan, kykenee luomaan heidän kaltaisensa. (الَّذِي خَلَقَ السَّمَاوَاتِ وَالْأَرْضَ قَادِرٌ عَلَى أَن يَخْلُقَ مِثْلَهُمْ) 17:99; 36:81
- Uskoville miehille ja uskoville naisille luvataan puutarhat, joiden alla virrat virtaavat, joissa he saavat asua ikuisesti. (الْمُؤْمِنِينَ وَالْمُؤْمِنَاتِ جَنَّاتٍ تَجْرِي مِن تَحْتِهَا الْأَنْهَارُ خَالِدِينَ فِيهَا) 9:72; 48:5
- Ja jos kysyt heiltä, kuka loi taivaat ja maan, he varmasti sanovat: "Jumala." Sano. (وَلَئِن سَأَلْتَهُم مَّنْ خَلَقَ السَّمَاوَاتِ وَالْأَرْضَ لَيَقُولُنَّ اللَّهُ قُلِ) 31:25; 39:38
- Ja totisesti, Me olemme esittäneet ihmisille tässä Koraanissa kaikenlaisia vertauksia. (وَلَقَدْ ضَرَبْنَا لِلنَّاسِ فِي هَذَا الْقُرْآنِ مِن كُلِّ مَثَلٍ) 30:58; 39:27
- Kun lähettiläämme tulivat Lootin luo, hän tuli murheelliseksi heidän tähtensä ja ahtaalle, ja hän sanoi. (جَاءَتْ رُسُلُنَا لُوطًا سِيءَ بِهِمْ وَضَاقَ بِهِمْ ذَرْعًا وَقَالَ) 11:77; 29:33
- Ja kun Me sanoimme enkeleille: "Kumartakaa Aadamille," he kumartuivat, paitsi Iblis, joka kieltäytyi. (وَإِذْ قُلْنَا لِلْمَلَائِكَةِ اسْجُدُوا لِآدَمَ فَسَجَدُوا إِلَّا إِبْلِيسَ أَبَى) 2:34; 20:116
- Ja maan Me levitimme ja asetimme siihen vuoria ja kasvatimme siinä kaikenlaista. (وَالْأَرْضَ مَدَدْنَاهَا وَأَلْقَيْنَا فِيهَا رَوَاسِيَ وَأَنبَتْنَا فِيهَا مِن كُلِّ) 15:19; 50:7
- He huusivat Jumalaa, vilpittöminä uskossaan Häntä kohtaan, mutta kun Hän pelasti heidät kuivalle maalle. (دَعَوُا اللَّهَ مُخْلِصِينَ لَهُ الدِّينَ فَلَمَّا نَجَّاهُمْ إِلَى الْبَرِّ) 29:65; 31:32
- Heille on juomaa kiehuvasta vedestä ja tuskallinen rangaistus, koska he olivat uskottomia. (لَهُمْ شَرَابٌ مِّنْ حَمِيمٍ وَعَذَابٌ أَلِيمٌ بِمَا كَانُوا يَكْفُرُونَ) 6:70; 10:4
- Kutsuisimmeko Jumalan ohella sellaista, joka ei hyödytä eikä vahingoita meitä? (أَنَدْعُو مِن دُونِ اللَّهِ مَا لَا يَنفَعُنَا وَلَا يَضُرُّنَا) 6:71; 10:106
- Että Jumala tietää, mitä taivaissa ja maan päällä on. (أَنَّ اللَّهَ يَعْلَمُ مَا فِي السَّمَاوَاتِ وَمَا فِي الْأَرْضِ) 5:97; 58:7
